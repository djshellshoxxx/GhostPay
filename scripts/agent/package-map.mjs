#!/usr/bin/env node
// Generate the workspace map read by the ghostpay-package-map agent skill, from every package.json and foundry.toml.
//   node scripts/agent/package-map.mjs           # rewrite .claude/skills/ghostpay-package-map/PACKAGE_MAP.md
//   node scripts/agent/package-map.mjs --check   # exit 1 if the committed map is stale
//   node scripts/agent/package-map.mjs --stdout  # print without writing
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dependents, internalDeps, loadRepo } from './workspaces.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const target = join(root, '.claude/skills/ghostpay-package-map/PACKAGE_MAP.md');

// Table cells: one line; escape backslashes first so an input `\|` cannot unescape the pipe that follows.
export const cell = (s) => String(s).replace(/\s+/g, ' ').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').trim();
// packages/x -> x; apps/x stays apps/x so the two groups remain distinguishable.
const short = (loc) => loc.replace(/^packages\//, '');

export function render({ workspaces, forge }) {
  const deps = internalDeps(workspaces);
  const rev = dependents(workspaces);
  const lines = [
    '<!-- GENERATED by scripts/agent/package-map.mjs. Do not edit by hand; rerun the script. -->',
    '# GhostPay workspace map',
    '',
    `${workspaces.length} npm workspaces and ${forge.length} Foundry projects. "Uses" and "Used by" list internal`,
    '`@ghostpay/*` edges only (dependencies, devDependencies, peer and optional). Names drop the `packages/` prefix.',
    '',
    '| Workspace | Purpose (package.json description) | Uses | Used by | Extra scripts |',
    '|---|---|---|---|---|',
  ];
  const standard = new Set(['build', 'typecheck', 'test', 'lint']);
  for (const w of workspaces) {
    const extra = w.scripts.filter((s) => !standard.has(s));
    const licence = w.license && w.license !== 'UNLICENSED' ? ` [licence: ${w.license}]` : '';
    lines.push(
      `| \`${short(w.location)}\` | ${cell(w.description || '(no description)')}${cell(licence)} | ` +
        `${(deps.get(w.location) ?? []).map(short).join(', ') || '-'} | ` +
        `${(rev.get(w.location) ?? []).map(short).join(', ') || '-'} | ${extra.join(', ') || '-'} |`,
    );
  }
  lines.push('', '## Foundry projects (no package.json; run `forge` inside the directory)', '');
  for (const p of forge) {
    const readme = join(root, p, 'README.md');
    const first = existsSync(readme)
      ? (readFileSync(readme, 'utf8')
          .split('\n')
          .find((l) => l.trim() && !l.startsWith('#')) ?? '')
      : '';
    // Drop markdown link targets: README-relative paths would break from the skill directory.
    const text = first.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1');
    lines.push(`- \`${p}\`: ${cell(text).slice(0, 200)}`);
  }
  lines.push('');
  return lines.join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const text = render(loadRepo(root));
  if (process.argv.includes('--stdout')) process.stdout.write(text);
  else if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== text) {
      console.error('PACKAGE_MAP.md is stale. Run: node scripts/agent/package-map.mjs');
      process.exit(1);
    }
    console.log('PACKAGE_MAP.md is current.');
  } else {
    writeFileSync(target, text);
    console.log(`Wrote ${target.replace(root, '')}`);
  }
}
