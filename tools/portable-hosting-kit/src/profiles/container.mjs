// @ts-check
// Container profile: a docker compose project running the nginx profile in nginxinc/nginx-unprivileged, pinned by
// digest, hardened like deploy/docker-compose.yml. Names below are a frozen contract (the Tor adapter attaches a
// service to CONTAINER_NETWORK and targets CONTAINER_SERVICE:CONTAINER_PORT).
//
// Project layout (all files relative to one directory):
//   compose.yaml        this profile
//   nginx/              nginx.conf (container main file) + hk-http.conf + hk-server.conf from generateNginx
//   www/                exportStatic() output (mounted read-only at CONTAINER_WWW_ROOT)

import { KitError, ERROR_CODES } from '../errors.mjs';
import { KIT_NAME, KIT_VERSION } from '../version.mjs';
import { assertLoopbackListener } from '../serve/preview.mjs';
import { checkBasePath } from '../serve/routing.mjs';
import { NGINX_HTTP_FILE, NGINX_SERVER_FILE, renderNginxMain } from './nginx.mjs';

/** @typedef {import('../types.mjs').HostConfig} HostConfig */
/** @typedef {{ name: string, data: Uint8Array }} OutFile */

/** Resolved 2026-10-27 from Docker Hub (tag list + registry manifest-list digest); see docs/SERVER-PROFILES.md. */
export const CONTAINER_IMAGE_REPO = 'nginxinc/nginx-unprivileged';
export const CONTAINER_IMAGE_TAG = '1.30.6-alpine';
export const CONTAINER_IMAGE_DIGEST = 'sha256:f5116ed4606f3eb015dd4a8e28cb9b351476dc0ad4bc6e9f93b19cec130cdf03';
export const CONTAINER_IMAGE = `${CONTAINER_IMAGE_REPO}:${CONTAINER_IMAGE_TAG}@${CONTAINER_IMAGE_DIGEST}`;

export const CONTAINER_SERVICE = 'web';
export const CONTAINER_PORT = 8080;
/** Internal network (no gateway); the Tor adapter's service joins it and proxies to web:8080. */
export const CONTAINER_NETWORK = 'site_internal';
/** Bridge used only to publish the loopback port; IP masquerading is disabled, so it gives no outbound NAT. */
export const CONTAINER_PUBLISH_NETWORK = 'site_publish';
export const CONTAINER_WWW_ROOT = '/srv/www';
export const CONTAINER_CONF_DIR = '/etc/nginx/hk';
export const CONTAINER_USER = '101:101';
export const COMPOSE_FILE = 'compose.yaml';

/**
 * @param {string} label
 * @returns {string} a valid compose project name
 */
export function composeProjectName(label) {
  const s = label.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^[-_]+|[-_]+$/g, '').slice(0, 40);
  return `hk-${s || 'site'}`;
}

/**
 * @param {HostConfig} hostConfig
 * @returns {string} the compose `ports` entry
 */
function publishSpec(hostConfig) {
  const l = hostConfig.listen;
  assertLoopbackListener(l);
  if (l.kind !== 'tcp') {
    throw new KitError(ERROR_CODES.UNSUPPORTED, 'the container profile publishes a loopback TCP port; a unix-socket listener is not supported');
  }
  if (l.port < 1) throw new KitError(ERROR_CODES.NETWORK_SCOPE, 'the container profile needs a fixed host port (1-65535)');
  return `${l.host === '::1' ? '[::1]' : l.host}:${l.port}:${CONTAINER_PORT}`;
}

/**
 * @param {HostConfig} hostConfig
 * @returns {string}
 */
function renderCompose(hostConfig) {
  const q = (/** @type {string} */ s) => JSON.stringify(s);
  const healthUrl = `http://127.0.0.1:${CONTAINER_PORT}${hostConfig.basePath}`;
  return [
    `# Generated by ${KIT_NAME} ${KIT_VERSION}. Static site served by nginx (unprivileged, read-only, no capabilities).`,
    '# Start: docker compose up -d   Stop and remove: docker compose down',
    `# Published on ${publishSpec(hostConfig)} only (loopback). Put TLS / Tor / I2P in front; never publish it publicly.`,
    `# Image pinned by digest (${CONTAINER_IMAGE_TAG}); to update, resolve a new digest and re-verify headers.`,
    `name: ${q(composeProjectName(hostConfig.mirrorLabel))}`,
    'services:',
    `  ${CONTAINER_SERVICE}:`,
    `    image: ${q(CONTAINER_IMAGE)}`,
    `    entrypoint: ["nginx", "-e", "stderr", "-c", ${q(`${CONTAINER_CONF_DIR}/nginx.conf`)}, "-g", "daemon off;"]`,
    `    user: ${q(CONTAINER_USER)}`,
    '    read_only: true',
    '    cap_drop: ["ALL"]',
    '    security_opt: ["no-new-privileges:true"]',
    '    tmpfs:',
    '      - "/tmp:size=16m,mode=1777,noexec,nosuid,nodev"',
    '    volumes:',
    '      - type: bind',
    '        source: ./www',
    `        target: ${q(CONTAINER_WWW_ROOT)}`,
    '        read_only: true',
    '        bind:',
    '          create_host_path: false',
    '      - type: bind',
    '        source: ./nginx',
    `        target: ${q(CONTAINER_CONF_DIR)}`,
    '        read_only: true',
    '        bind:',
    '          create_host_path: false',
    '    ports:',
    `      - ${q(publishSpec(hostConfig))}`,
    '    networks:',
    `      - ${CONTAINER_NETWORK}`,
    `      - ${CONTAINER_PUBLISH_NETWORK}`,
    '    mem_limit: 128m',
    '    memswap_limit: 128m',
    '    cpus: 0.5',
    '    pids_limit: 64',
    '    stop_signal: SIGQUIT',
    '    restart: unless-stopped',
    '    logging:',
    '      driver: local',
    '      options: { max-size: "1m", max-file: "2" }',
    '    healthcheck:',
    `      test: ["CMD", "wget", "-q", "-O", "/dev/null", ${q(healthUrl)}]`,
    '      interval: 30s',
    '      timeout: 5s',
    '      retries: 3',
    '      start_period: 5s',
    '      start_interval: 1s',
    'networks:',
    `  ${CONTAINER_NETWORK}:`,
    '    internal: true',
    `  ${CONTAINER_PUBLISH_NETWORK}:`,
    '    driver: bridge',
    '    driver_opts:',
    '      com.docker.network.bridge.enable_ip_masquerade: "false"',
    '',
  ].join('\n');
}

/**
 * Generate the compose project. `nginxFiles` are generateNginx()'s files; their http/server parts are reused
 * with a container main file (listen 8080 inside the container's network namespace, root CONTAINER_WWW_ROOT).
 * @param {{ hostConfig: HostConfig, nginxFiles: OutFile[] }} a
 * @returns {{ files: OutFile[] }}
 */
export function generateContainer({ hostConfig, nginxFiles }) {
  checkBasePath(hostConfig.basePath);
  const part = (/** @type {string} */ name) => {
    const f = nginxFiles.find((x) => x.name === name);
    if (!f) throw new KitError(ERROR_CODES.USAGE, `nginxFiles lacks ${name}; pass generateNginx().files`);
    return f;
  };
  const httpPart = part(NGINX_HTTP_FILE);
  const serverPart = part(NGINX_SERVER_FILE);
  const main = renderNginxMain({
    listen: `listen ${CONTAINER_PORT} default_server;`,
    root: CONTAINER_WWW_ROOT,
    pidFile: '/tmp/nginx.pid',
    tempDir: '/tmp',
    comment: [
      'Container main file: listens on 8080 inside the container network namespace only; the host publishes it on',
      'loopback (compose.yaml) and the internal network site_internal. Read-only root filesystem, /tmp is tmpfs.',
    ],
  });
  const enc = new TextEncoder();
  return {
    files: [
      { name: COMPOSE_FILE, data: enc.encode(renderCompose(hostConfig)) },
      { name: 'nginx/nginx.conf', data: enc.encode(main) },
      { name: `nginx/${NGINX_HTTP_FILE}`, data: httpPart.data },
      { name: `nginx/${NGINX_SERVER_FILE}`, data: serverPart.data },
    ],
  };
}
