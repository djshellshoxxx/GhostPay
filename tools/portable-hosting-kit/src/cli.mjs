/**
 * Refuse to replace a non-empty directory that this kit did not generate.
 * @param {string} outDir
 * @param {string} markerFile
 */
async function assertReplaceable(outDir, markerFile) {
  /** @type {string[]} */
  let entries;
  try {
    entries = await readdir(outDir);
  } catch (e) {
    if (/** @type {NodeJS.ErrnoException} */ (e).code === 'ENOENT') return;
    throw e;
  }
  if (entries.length === 0) return;
  const text = await readFile(join(outDir, markerFile), 'utf8').catch(() => '');
  if (!text.includes(OUTPUT_MARKER)) usage(`refusing to replace ${outDir}: it is not empty and was not generated by this kit (no ${markerFile} marker)`);
}

const ALL_PROFILES = ['static', 'nginx', 'container', 'tor', 'i2p'];

/**
 * Generate hosting profiles for a verified archive into outDir (atomic replace).
 * @param {{ target: string, outDir: string, host: HostConfig, with: string[], o: Record<string, unknown> }} p
 * @returns {Promise<{ outDir: string, generated: string[], warnings: string[] }>}
 */
export async function generateProfiles(p) {
  const opened = await openVerified(p.target, p.o);
  try {
    const policy = await policyFor(opened.siteDir, opened.manifest);
    const files = opened.manifest.content.files.map((f) => f.path);
    const entrypoint = opened.manifest.content.entrypoint;
    const wwwRoot = /** @type {string | undefined} */ (p.o['www-root']) ?? '/srv/ghostpay-site/www';
    if (!wwwRoot.startsWith('/') || wwwRoot.split('/').includes('..')) usage('--www-root must be an absolute path without ".." segments');
    /** @type {string[]} */
    const warnings = [];
    /** @type {string[]} */
    const generated = [];
    const overlay = overlayCollides(files) ? null : buildMirrorOverlay(opened.manifest, p.host, opened.archiveSha256);
    if (overlay === null) warnings.push('site uses _mirror/: no mirror.json overlay generated');
    const served = overlay === null ? files : [...files, overlay.path];
    const forbiddenRoots = [p.outDir, opened.topDir, wwwRoot];
    if (p.host.basePath !== '/') warnings.push(`base path ${p.host.basePath}: the app shares its origin's storage and permissions with every other path on that host (audit WEB-APP-03); serve nothing else on this origin`);
    await assertReplaceable(p.outDir, 'PROFILE-README.md');
    await mkdir(dirname(p.outDir), { recursive: true });
    await replaceDirAtomic(p.outDir, async (tmp) => {
      const enc = new TextEncoder();
      /**
       * @param {string} sub
       * @param {Array<{ name: string, data: Uint8Array | string }>} list
       */
      const writeAll = async (sub, list) => {
        for (const f of list) {
          const target = join(tmp, sub, ...f.name.split('/'));
          await mkdir(dirname(target), { recursive: true });
          await writeFileAtomic(target, typeof f.data === 'string' ? enc.encode(f.data) : f.data);
          generated.push(`${sub}/${f.name}`);
        }
      };
      await writeAll('.', [{ name: 'host-config.json', data: serializeHostConfig(p.host) }]);
      if (p.with.includes('static')) {
        await exportStatic({ siteDir: opened.siteDir, files, entrypoint, hostConfig: p.host, policy, outDir: join(tmp, 'static'), overlayFiles: overlay === null ? [] : [overlay] });
        generated.push('static/');
      }
      if (p.with.includes('nginx') || p.with.includes('container')) {
        const nginx = generateNginx({ files: served, entrypoint, hostConfig: p.host, policy, wwwRoot });
        if (p.with.includes('nginx')) await writeAll('nginx', nginx.files);
        if (p.with.includes('container')) {
          // container/ is a self-contained stack: compose.yaml mounts ./www and ./nginx next to itself, and a Tor
          // container override (tor/compose.tor.yml) resolves ./tor relative to it.
          await exportStatic({ siteDir: opened.siteDir, files, entrypoint, hostConfig: p.host, policy, outDir: join(tmp, 'container'), overlayFiles: overlay === null ? [] : [overlay] });
          generated.push('container/www/');
          await writeAll('container', generateContainer({ hostConfig: p.host, nginxFiles: nginx.files }).files);
        }
      }
      if (p.with.includes('tor')) {
        const mode = /** @type {string | undefined} */ (p.o['tor-instance']) ?? 'system';
        /** @type {Parameters<typeof generateTorProfile>[0]['instance']} */
        let instance;
        if (mode === 'system') instance = { mode: 'system' };
        else if (mode === 'dedicated') instance = { mode: 'dedicated', dataDirectory: /** @type {string | undefined} */ (p.o['tor-data-dir']) ?? '/var/lib/tor-ghostpay-site' };
        else if (mode === 'container') {
          if (!p.with.includes('container')) usage('--tor-instance container needs the container profile too (--with ...,container,tor)');
          instance = { mode: 'container' };
        }
        else return usage('--tor-instance must be system, dedicated or container');
        const tor = generateTorProfile({
          hostConfig: p.host,
          hiddenServiceDir: /** @type {string | undefined} */ (p.o['hs-dir']) ?? '/var/lib/tor/ghostpay-site',
          target: mode === 'container' ? 'compose-service' : 'host-listener',
          instance,
          forbiddenRoots,
        });
        await writeAll(mode === 'container' ? 'container' : '.', tor.files);
        warnings.push(...tor.warnings);
      }
      if (p.with.includes('i2p')) {
        const router = /** @type {string | undefined} */ (p.o['i2p-router']) ?? 'i2pd';
        if (router !== 'i2pd' && router !== 'java-i2p') usage('--i2p-router must be i2pd or java-i2p');
        const i2p = generateI2pProfile({
          hostConfig: p.host,
          router,
          tunnelName: /** @type {string | undefined} */ (p.o['tunnel-name']) ?? 'ghostpay-site',
          target: 'host-listener',
          keysFile: /** @type {string | undefined} */ (p.o['i2p-keys']) ?? 'ghostpay-site.dat',
          forbiddenRoots,
        });
        await writeAll('.', i2p.files);
        warnings.push(...i2p.warnings);
      }
      await writeAll('.', [{ name: 'PROFILE-README.md', data: profileReadme(opened.manifest, p.host, generated, warnings) }]);
    });
    return { outDir: p.outDir, generated, warnings };
  } finally {
    await opened.cleanup();
  }
}

/**
 * @param {HostingManifest} m
 * @param {HostConfig} host
 * @param {string[]} generated
 * @param {string[]} warnings
 * @returns {string}
 */
function profileReadme(m, host, generated, warnings) {
  return `${OUTPUT_MARKER}
# Hosting profiles for ${m.appId} ${m.provenance.label}

Content digest: \`${m.content.digest}\`
Transport: ${host.transport}; base path: \`${host.basePath}\`; listener: ${host.listen.kind === 'tcp' ? `${host.listen.host}:${host.listen.port}` : `unix:${host.listen.path}`}

Generated by ${KIT_NAME} ${KIT_VERSION}. **Nothing here has been installed, started or published.** Review every file,
then activate what you need by hand (see tools/portable-hosting-kit/README.md and docs/TOR.md, docs/I2P.md). Files:

${generated.map((g) => `- \`${g}\``).join('\n')}

${warnings.length > 0 ? `Warnings:\n\n${warnings.map((w) => `- ${w}`).join('\n')}\n` : ''}
- \`static/www\` is a byte-identical copy of the site under the base path plus the \`_mirror/mirror.json\` overlay.
  Header-less static hosts are **unsupported**: they cannot send the required CSP and other headers.
- Keys and identities (Tor HiddenServiceDir, I2P destination keys, TLS keys) are never in this directory.
  Keep them out of it; this directory is replaced wholesale on the next \`profile\` run.
- Onion or I2P delivery does not anonymise wallet, RPC or chain activity. Mirrors are separate origins.
`;
}

/**
 * @param {Record<string, unknown>} o
 * @param {string[]} pos
 * @param {Io} io
 */
async function cmdProfile(o, pos, io) {
  const target = pos[0] ?? usage('profile needs <archive.zip | unpacked-dir>');
  const config = /** @type {string | undefined} */ (o['config']) ?? usage('profile needs --config host.json (create one with "ghostpay-host wizard")');
  const out = /** @type {string | undefined} */ (o['out']) ?? usage('profile needs --out <dir>');
  /** @type {unknown} */
  let raw;
  try {
    raw = JSON.parse(await readFile(resolve(io.cwd, config), 'utf8'));
  } catch (e) {
    throw new KitError(ERROR_CODES.CONFIG, `cannot read ${config}: ${e instanceof Error ? e.message : String(e)}`);
  }
  const host = parseHostConfig(raw);
  if (host.basePath !== '/' && o['allow-shared-origin'] !== true) {
    usage(`basePath ${host.basePath} shares its origin (cookies, localStorage, IndexedDB, permissions) with everything else served on that host. GhostPay needs a dedicated origin (audit WEB-APP-03). Pass --allow-shared-origin only for an origin that serves nothing else.`);
  }
  const requested = /** @type {string | undefined} */ (o['with']);
  const withList = requested === undefined ? defaultProfilesFor(host) : requested.split(',').map((s) => s.trim()).filter(Boolean);
  for (const w of withList) if (!ALL_PROFILES.includes(w)) usage(`--with: unknown profile ${w} (choose from ${ALL_PROFILES.join(', ')})`);
  if (withList.includes('tor') && host.transport !== 'onion') usage('the tor profile needs a host config with transport "onion"');
  if (withList.includes('i2p') && host.transport !== 'i2p') usage('the i2p profile needs a host config with transport "i2p"');
  const r = await generateProfiles({ target: resolve(io.cwd, target), outDir: resolve(io.cwd, out), host, with: withList, o });
  if (o['json'] === true) io.out(`${JSON.stringify(r, null, 2)}\n`);
  else {
    io.out(`generated (inert, nothing started): ${r.outDir}\n`);
    for (const g of r.generated) io.out(`  ${g}\n`);
    for (const w of r.warnings) io.out(`  warn ${w}\n`);
  }
  return EXIT.OK;
}

/**
 * @param {HostConfig} host
 * @returns {string[]}
 */
function defaultProfilesFor(host) {
  if (host.transport === 'onion') return ['static', 'nginx', 'container', 'tor'];
  if (host.transport === 'i2p') return ['static', 'nginx', 'container', 'i2p'];
  return ['static', 'nginx', 'container'];
}

