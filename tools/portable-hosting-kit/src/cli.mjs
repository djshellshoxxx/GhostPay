/** @type {Record<string, (o: Record<string, unknown>, pos: string[], io: Io) => Promise<number>>} */
const COMMANDS = { validate: cmdValidate, package: cmdPackage, verify: cmdVerify, preview: cmdPreview, profile: cmdProfile, wizard: cmdWizard, demo: cmdDemo };

/**
 * @param {string[]} argv arguments after the program name
 * @param {Partial<Io>} [ioIn]
 * @returns {Promise<number>} exit code
 */
export async function main(argv, ioIn = {}) {
  /** @type {Io} */
  const io = {
    out: ioIn.out ?? ((s) => process.stdout.write(s)),
    err: ioIn.err ?? ((s) => process.stderr.write(s)),
    cwd: ioIn.cwd ?? process.cwd(),
    env: ioIn.env ?? process.env,
    ...(ioIn.stdin === undefined ? {} : { stdin: ioIn.stdin }),
    ...(ioIn.waitForStop === undefined ? {} : { waitForStop: ioIn.waitForStop }),
  };
  const [command, ...rest] = argv;
  if (command === undefined || command === '--help' || command === '-h' || command === 'help') {
    io.out(USAGE);
    return command === undefined ? EXIT.USAGE : EXIT.OK;
  }
  if (command === '--version') {
    io.out(`${KIT_VERSION}\n`);
    return EXIT.OK;
  }
  const fn = COMMANDS[command];
  if (fn === undefined) {
    io.err(`unknown command: ${command}\n\n${USAGE}`);
    return EXIT.USAGE;
  }
  try {
    const { values, positionals } = parseArgs({ args: rest, options: OPTIONS, allowPositionals: true, strict: true });
    if (values['help'] === true) {
      io.out(USAGE);
      return EXIT.OK;
    }
    return await fn(values, positionals, io);
  } catch (e) {
    if (isKitError(e)) {
      io.err(`error ${e.code}: ${termSafe(e.message)}\n`);
      return e.code === ERROR_CODES.USAGE ? EXIT.USAGE : e.code === ERROR_CODES.IO ? EXIT.INTERNAL : EXIT.FAILED;
    }
    if (e instanceof TypeError && /** @type {NodeJS.ErrnoException} */ (e).code?.startsWith('ERR_PARSE_ARGS')) {
      io.err(`error E_USAGE: ${e.message}\n`);
      return EXIT.USAGE;
    }
    const errno = /** @type {NodeJS.ErrnoException} */ (e);
    if (typeof errno?.code === 'string' && /^E[A-Z]+$/.test(errno.code)) {
      io.err(`error E_IO: ${errno.message}\n`);
      return EXIT.INTERNAL;
    }
    io.err(`internal error: ${e instanceof Error ? (e.stack ?? e.message) : String(e)}\n`);
    return EXIT.INTERNAL;
  }
}

