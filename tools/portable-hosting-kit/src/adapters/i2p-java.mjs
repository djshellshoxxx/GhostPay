// @ts-check
// Java I2P renderer: one split-format file for i2ptunnel.config.d/. Format per the I2P configuration spec
// (i2p.net/en/docs/specs/configuration, "I2PTunnel"): since 0.9.42 split files carry the properties WITHOUT the
// "tunnel.N." prefix. Confirmed in i2p.i2p TunnelControllerGroup.loadConfig(): a file whose first key starts with
// "tunnel." is parsed as monolithic, otherwise as one split tunnel; only "*.config" files are loaded, sorted by name.
// Property names confirmed in TunnelController.java / I2PTunnelHTTPServer.java / I2PTunnelServer.java.
// NOT verified at runtime: Java I2P is not installed in the test environment.

/** @typedef {import('./i2p.mjs').I2pTunnelSpec} I2pTunnelSpec */

/**
 * Upstream defaults that TunnelController applies to a server tunnel when no limit is set (TunnelController.java
 * DEFAULT_MAX_*). Written explicitly so the operator sees and can tune them.
 */
export const JAVA_STREAMING_LIMITS = Object.freeze({
  'i2p.streaming.maxConnsPerMinute': 30,
  'i2p.streaming.maxConnsPerHour': 80,
  'i2p.streaming.maxConnsPerDay': 200,
  'i2p.streaming.maxTotalConnsPerMinute': 50,
  'i2p.streaming.maxConcurrentStreams': 30,
});

/**
 * Router naming convention is "NN-<name>-i2ptunnel.config"; 90 sorts after the default tunnels.
 * @param {string} tunnelName
 */
export function javaTunnelFileName(tunnelName) {
  return `90-${tunnelName}-i2ptunnel.config`;
}

/**
 * @param {I2pTunnelSpec} s
 * @returns {string}
 */
export function renderJavaTunnel(s) {
  const lines = [
    `# Java I2P HTTP server tunnel for "${s.description}". Generated by ghostpay-portable-hosting-kit.`,
    '# INERT: copy into <I2P config dir>/i2ptunnel.config.d/ after review; startOnLoad=false until you enable it.',
    `# Contains no keys: the router creates <config dir>/${s.keysFile} on first start (and a copy in i2ptunnel-keyBackup/).`,
    '# Split format: no "tunnel.N." prefixes. Values must not contain "#". Sources: docs/I2P.md.',
    `name=${s.tunnelName}`,
    `description=${s.description}`,
    'type=httpserver',
    `targetHost=${s.host}`,
    `targetPort=${s.port}`,
    `privKeyFile=${s.keysFile}`,
  ];
  if (s.b32Host) lines.push(`spoofedHost=${s.b32Host}`);
  lines.push(
    'startOnLoad=false',
    '# Do not originate local connections from a per-visitor 127.x.y.z address.',
    'option.enableUniqueLocal=false',
    '# Refuse requests that arrive through a clearnet inproxy (this is an I2P-only mirror).',
    'option.rejectInproxy=true',
    '# Keep 3-hop tunnels.',
    'option.inbound.length=3',
    'option.outbound.length=3',
    '# Inbound limits (upstream defaults). Each request is a new stream: raise them if a full page load is refused.',
    ...Object.entries(JAVA_STREAMING_LIMITS).map(([k, v]) => `option.${k}=${v}`),
    '',
  );
  return lines.join('\n');
}

/**
 * @param {I2pTunnelSpec} s
 * @param {string} configName
 * @returns {string}
 */
export function renderJavaReadme(s, configName) {
  return [
    '# I2P (Java I2P) server tunnel profile (generated)',
    '',
    'Nothing here is active. Java I2P was not available to the kit for runtime validation: the format follows the',
    'official configuration spec and the i2p.i2p source. See docs/I2P.md for the full guide, sources and limits.',
    '',
    `- Tunnel file: \`${configName}\` (type \`httpserver\`)`,
    `- Target: \`${s.host}:${s.port}\``,
    `- Identity: \`<I2P config dir>/${s.keysFile}\` (created on first start if missing, plus a copy in \`i2ptunnel-keyBackup/\`)`,
    `- Address: ${s.b32Host ?? 'not known yet: read it from the router console tunnel page (127.0.0.1:7657, local only)'}`,
    '',
    '## Install',
    '',
    '1. Review the file. Copy it into `<I2P config dir>/i2ptunnel.config.d/` (user installs: `~/.i2p/`).',
    '   The router only uses the split directory when its config dir differs from its install dir; for a portable',
    '   install enter the same values in the console tunnel wizard (127.0.0.1:7657/i2ptunnel/) instead.',
    '2. Restart the router (or the I2PTunnel client) so the file is loaded, then start the tunnel from the console.',
    '   Set `startOnLoad=true` once you are satisfied.',
    `3. Restrict permissions on \`${s.keysFile}\` and on \`i2ptunnel-keyBackup/\`.`,
    '',
    '## Identity backup',
    '',
    `\`${s.keysFile}\` (and its automatic copy in \`i2ptunnel-keyBackup/\`) is the destination's private key. Back it`,
    'up offline and encrypted; never add it to a site bundle, archive, repository or container image.',
    '',
    '## Never expose',
    '',
    'The router console (7657/7667), HTTP/HTTPS proxies (4444/4445), I2CP (7654), SAM (7656), I2PControl (7650)',
    'are management/client ports, never website targets.',
    '',
  ].join('\n');
}
