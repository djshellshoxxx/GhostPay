// @ts-check
// i2pd renderer: one INI section for tunnels.d/<name>.conf. Option names verified in the i2pd 2.49.0 source
// (libi2pd_client/ClientContext.h/.cpp) and in the current docs (docs.i2pd.website user-guide/tunnels). Comments are
// on their own lines: boost's INI parser has no inline comments.

/** @typedef {import('./i2p.mjs').I2pTunnelSpec} I2pTunnelSpec */

/**
 * @param {I2pTunnelSpec} s
 * @returns {string}
 */
export function renderI2pdTunnel(s) {
  const lines = [
    `# i2pd HTTP server tunnel for "${s.description}". Generated by ghostpay-portable-hosting-kit.`,
    '# INERT until an operator copies it into the i2pd tunnels directory. Contains no keys: i2pd creates',
    `# <datadir>/${s.keysFile} on first start (the I2P identity). Back it up offline; never put it into a site bundle.`,
    '# Sources: docs/I2P.md.',
    `[${s.tunnelName}]`,
    'type = http',
    `host = ${s.host}`,
    `port = ${s.port}`,
    '# I2P-side port; 80 lets visitors use http://<b32>.b32.i2p/ without a port.',
    `inport = ${s.inport}`,
    '# Router-relative: resolved as <datadir>/<keys>.',
    `keys = ${s.keysFile}`,
    '# EdDSA-SHA512-Ed25519 (i2pd default, written explicitly).',
    'signaturetype = 7',
    '# Keep the default 3-hop tunnels; shorter tunnels weaken the server\'s anonymity.',
    'inbound.length = 3',
    'outbound.length = 3',
    '# Do not map each visitor to a distinct 127.x.y.z source address (a per-visitor handle in web server logs).',
    'enableuniquelocal = false',
    '# Do not add X-I2P-DestHash/DestB64/DestB32 visitor headers. Honoured by i2pd >= 2.59.0 only;',
    '# older versions ignore this key and always send the headers (do not log them).',
    'i2pheaders = false',
  ];
  if (s.b32Host) {
    lines.push('# Host header sent to the web server (default would be the "host" value above).', `hostoverride = ${s.b32Host}`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * @param {I2pTunnelSpec} s
 * @param {string} configName
 * @returns {string}
 */
export function renderI2pdReadme(s, configName) {
  return [
    '# I2P (i2pd) server tunnel profile (generated)',
    '',
    'Nothing here is active. See docs/I2P.md for the full guide, sources and limits.',
    '',
    `- Tunnel file: \`${configName}\` (section \`[${s.tunnelName}]\`, type \`http\`)`,
    `- Forwards I2P port ${s.inport} to \`${s.host}:${s.port}\``,
    `- Identity: \`<i2pd datadir>/${s.keysFile}\` (created by i2pd on first start if missing)`,
    `- Address: ${s.b32Host ?? 'not known yet: read it from the i2pd web console (127.0.0.1:7070, local only) after first start'}`,
    '',
    '## Install',
    '',
    '1. Review the tunnel file. Copy it into the i2pd tunnels directory: Debian/Ubuntu packages use',
    '   `/etc/i2pd/tunnels.conf.d/` (`--tunnelsdir`); otherwise `~/.i2pd/tunnels.d/` or `/var/lib/i2pd/tunnels.d/`.',
    '   Only files ending in `.conf` are loaded.',
    '2. Reload tunnels (`systemctl reload i2pd` sends SIGHUP) or restart i2pd. i2pd has no config-check mode.',
    `3. Restrict the key file: \`chmod 600 <datadir>/${s.keysFile}\` (i2pd < 3.0.0 creates it with the process umask).`,
    '',
    '## Identity backup',
    '',
    `\`${s.keysFile}\` is the destination's private key. Copy it offline and encrypted; anyone holding it can`,
    'impersonate the site. Never add it to a site bundle, archive, repository or container image.',
    '',
    '## Never expose',
    '',
    'The i2pd web console (7070), HTTP/SOCKS proxies (4444/4447), SAM (7656), I2CP (7654), I2PControl (7650) and',
    'BOB (2827) are management/client ports, never website targets.',
    '',
  ].join('\n');
}
