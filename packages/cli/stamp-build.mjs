import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const packageRoot = fileURLToPath(new URL('.', import.meta.url));
// Metadata belongs to this checkout, regardless of inherited Git routing/config overrides.
const gitEnvironment = { ...process.env };
for (const name of Object.keys(gitEnvironment)) if (/^GIT_/i.test(name)) delete gitEnvironment[name];

function git(args) {
  const result = spawnSync('git', ['--no-optional-locks', '-c', 'core.fsmonitor=false', ...args], {
    cwd: packageRoot, env: gitEnvironment, encoding: 'utf8', timeout: 5000, maxBuffer: 1024 * 1024,
    stdio: ['ignore', 'pipe', 'ignore'],
  });
  return result.error === undefined && result.status === 0 ? result.stdout.trim() : undefined;
}

// This script runs only at build time. Runtime diagnostics neither spawn Git nor inspect credentials.
const revision = git(['rev-parse', '--verify', 'HEAD']);
const status = revision !== undefined && /^[0-9a-f]{40}$/.test(revision)
  ? git(['status', '--porcelain=v1', '--untracked-files=normal']) : undefined;
const stableRevision = status === undefined ? undefined : git(['rev-parse', '--verify', 'HEAD']);
const buildInfo = status !== undefined && revision === stableRevision
  ? { sourceRevision: revision, dirty: status !== '' }
  : { sourceRevision: null, dirty: null };

// No timestamp, host path or environment data enters the reproducible module.
writeFileSync(new URL('./dist/build-info.js', import.meta.url),
  `// Generated by stamp-build.mjs after compilation.\nexport const BUILD_INFO = Object.freeze(${JSON.stringify(buildInfo)});\n`, 'utf8');
