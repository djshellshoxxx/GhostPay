// Generates test-vectors/shielded-pool.json (deterministic, no randomness) and, when the
// INSECURE DEV CEREMONY artefacts exist, proof fixtures in fixtures/*.json (random proofs).
// Usage: npm run build -w @ghostpay/pool-circuits && node scripts/gen-vectors.mjs [--no-proofs]
import { writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encodeAbiParameters, encodePacked, keccak256 } from 'viem';
import * as snarkjs from 'snarkjs';
import {
  LeanImt, SNARK_SCALAR_FIELD as P, MAX_TREE_DEPTH, buildWithdrawInputs, buildRagequitInputs,
  commitment, hashNode, nullifierHash, precommitment, toVerifierCalldata,
} from '../dist/index.js';
import { poseidon1, poseidon2, poseidon3 } from 'poseidon-lite';

const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = join(PKG, '..', '..');
const s = (x) => x.toString();
// Deterministic "random-looking" field elements: keccak256("ghostpay/pool-vectors/" || tag) mod P.
const fe = (tag) => BigInt(keccak256(new TextEncoder().encode(`ghostpay/pool-vectors/${tag}`))) % P;

const poseidon = {
  t2: [0n, 1n, 2n, P - 1n, fe('p1')].map((a) => ({ in: [s(a)], out: s(poseidon1([a])) })),
  t3: [[0n, 0n], [1n, 2n], [P - 1n, P - 1n], [fe('p2a'), fe('p2b')]].map((v) => ({ in: v.map(s), out: s(poseidon2(v)) })),
  t4: [[0n, 0n, 0n], [1n, 2n, 3n], [P - 1n, 0n, 1n], [fe('p3a'), fe('p3b'), fe('p3c')]].map((v) => ({ in: v.map(s), out: s(poseidon3(v)) })),
};

const leanImt = [];
const t = new LeanImt();
const leaves = [];
for (let n = 1; n <= 33; n++) {
  const leaf = fe(`leaf/${n}`);
  t.insert(leaf);
  leaves.push(s(leaf));
  const idx = [...new Set([0, n - 1, Math.floor(n / 2)])];
  leanImt.push({
    size: n, depth: t.depth, root: s(t.root()),
    paths: idx.map((i) => { const p = t.path(i); return { index: i, siblings: p.siblings.slice(0, Math.max(p.depth, 1)).map(s) }; }),
  });
}

const notes = [0, 1, 2].map((k) => {
  const value = [1n, 10n ** 18n, (1n << 128n) - 1n][k];
  const label = fe(`label/${k}`); const nullifier = fe(`nullifier/${k}`); const secret = fe(`secret/${k}`);
  const pre = precommitment(nullifier, secret);
  return { value: s(value), label: s(label), nullifier: s(nullifier), secret: s(secret), precommitment: s(pre),
    commitment: s(commitment(value, label, pre)), nullifierHash: s(nullifierHash(nullifier)) };
});

// Contract-side derivations (spec shielded-pool.md 6.1; contract is authoritative, cross-check in pool-contracts).
const pool = '0x00000000000000000000000000000000000000a1';
const asset = '0x00000000000000000000000000000000000000b2';
const chainId = 31337n;
const scope = BigInt(keccak256(encodeAbiParameters([{ type: 'address' }, { type: 'uint256' }, { type: 'address' }], [pool, chainId, asset]))) % P;
const labels = [1n, 2n].map((nonce) => ({ nonce: s(nonce), label: s(BigInt(keccak256(encodePacked(['uint256', 'uint256'], [scope, nonce]))) % P) }));
const withdrawalAbi = [{ type: 'tuple', components: [
  { name: 'recipient', type: 'address' }, { name: 'relayer', type: 'address' }, { name: 'relayerFee', type: 'uint256' },
  { name: 'feeTo', type: 'address' }, { name: 'deadline', type: 'uint256' }, { name: 'aspPublisher', type: 'address' },
  { name: 'announce', type: 'bytes' } ] }, { type: 'uint256' }];
const withdrawal = { recipient: '0x00000000000000000000000000000000000000c3', relayer: '0x00000000000000000000000000000000000000d4',
  relayerFee: 1000n, feeTo: '0x00000000000000000000000000000000000000e5', deadline: 1_900_000_000n,
  aspPublisher: '0x0000000000000000000000000000000000000000', announce: '0x' };
const context = BigInt(keccak256(encodeAbiParameters(withdrawalAbi, [withdrawal, scope]))) % P;

// Deterministic withdraw witness example (public signals computed from the hashes, no proof).
const n0 = { value: 1_000_000n, label: BigInt(labels[0].label), nullifier: fe('w/nullifier'), secret: fe('w/secret') };
const st = new LeanImt();
for (let i = 0; i < 5; i++) st.insert(i === 2 ? commitment(n0.value, n0.label, precommitment(n0.nullifier, n0.secret)) : fe(`w/other/${i}`));
const asp = new LeanImt();
asp.insert(BigInt(labels[1].label)); asp.insert(n0.label);
const wIn = buildWithdrawInputs({ chainId: 31337, note: n0, statePath: st.path(2), aspPath: asp.path(1), withdrawnValue: 400_000n,
  newNullifier: fe('w/newNullifier'), newSecret: fe('w/newSecret'), context });
const wPub = [s(commitment(600_000n, n0.label, precommitment(BigInt(wIn.newNullifier), BigInt(wIn.newSecret)))), s(nullifierHash(n0.nullifier)),
  wIn.withdrawnValue, wIn.stateRoot, wIn.stateTreeDepth, wIn.aspEnabled, wIn.ASPRoot, wIn.ASPTreeDepth, wIn.context];

const out = {
  description: 'GhostPay shielded-pool cross-language vectors (Poseidon circomlib/poseidon-lite, LeanIMT, commitments, scope/label/context, withdraw witness). Generated by packages/pool-circuits/scripts/gen-vectors.mjs; deterministic. TESTNET PoC.',
  version: 1,
  field: s(P),
  maxTreeDepth: MAX_TREE_DEPTH,
  poseidon,
  leanImt: { leafRule: 'leaf n (1-based) = keccak256("ghostpay/pool-vectors/leaf/" + n) mod P', leaves, trees: leanImt,
    pathNote: 'siblings bottom-up, 0 = no sibling at that level (LeanIMT propagation); circuit pads to 32 with 0' },
  notes,
  contract: { note: 'derived per docs/remote/privacy-specs/shielded-pool.md 6.1 with viem; the Solidity contract is authoritative',
    pool, asset, chainId: s(chainId), scope: s(scope), labels, withdrawal: { ...withdrawal, relayerFee: s(withdrawal.relayerFee), deadline: s(withdrawal.deadline) }, context: s(context) },
  withdrawExample: { input: wIn, publicSignals: wPub, order: ['newCommitmentHash', 'existingNullifierHash', 'withdrawnValue', 'stateRoot', 'stateTreeDepth', 'aspEnabled', 'ASPRoot', 'ASPTreeDepth', 'context'] },
  ragequitExample: { input: buildRagequitInputs(31337, { value: BigInt(notes[1].value), label: BigInt(notes[1].label), nullifier: BigInt(notes[1].nullifier), secret: BigInt(notes[1].secret) }),
    publicSignals: [notes[1].commitment, notes[1].nullifierHash, notes[1].value, notes[1].label] },
};
void hashNode;
writeFileSync(join(ROOT, 'test-vectors', 'shielded-pool.json'), JSON.stringify(out, null, 2) + '\n');
console.log('wrote test-vectors/shielded-pool.json');

const wasm = join(PKG, 'build/withdraw32_js/withdraw32.wasm');
const zkey = join(PKG, 'build/withdraw32_final.zkey');
if (process.argv.includes('--no-proofs') || !existsSync(zkey)) { console.log('skipping proof fixtures'); process.exit(0); }
const HDR = 'INSECURE DEV CEREMONY proof fixture: keys are forgeable; testnet/anvil only. Layout: INTERFACE.md section 4.';
async function fixture(name, kind, input, wasmP, zkeyP, n) {
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, wasmP, zkeyP);
  const cd = toVerifierCalldata(proof, publicSignals, n);
  writeFileSync(join(PKG, 'fixtures', `${name}.json`), JSON.stringify({ warning: HDR, kind, ...cd, input }, null, 2) + '\n');
  console.log(`wrote fixtures/${name}.json`);
}
await fixture('withdraw-asp', 'withdraw', wIn, wasm, zkey, 9);
const wNoAsp = buildWithdrawInputs({ chainId: 31337, note: n0, statePath: st.path(2), withdrawnValue: 1_000_000n,
  newNullifier: fe('w2/newNullifier'), newSecret: fe('w2/newSecret'), context });
await fixture('withdraw-noasp-full', 'withdraw', wNoAsp, wasm, zkey, 9);
await fixture('ragequit', 'ragequit', out.ragequitExample.input, join(PKG, 'build/commitment_js/commitment.wasm'), join(PKG, 'build/commitment_final.zkey'), 4);
process.exit(0);
