#!/usr/bin/env bash
# =====================================================================================
#  INSECURE DEV CEREMONY  --  DO NOT USE FOR ANYTHING HOLDING VALUE
# =====================================================================================
#  By default there are NO secret contributions: phase 1 and phase 2 consist only of
#  snarkjs "beacon" steps with the FIXED, PUBLIC beacon value below. The toxic waste
#  (tau, alpha, beta, delta) is therefore recomputable by anyone who reads this file,
#  and anyone can FORGE Groth16 proofs for these keys and DRAIN any pool that uses the
#  resulting verifiers. This is intentional: the build is reproducible byte-for-byte
#  (same circom / snarkjs / circomlib => same zkey and verifier) and the insecurity is
#  impossible to miss.
#
#  POOL_CEREMONY_CONTRIBUTE=1 adds two snarkjs contributions per phase. snarkjs mixes 64
#  bytes of OS randomness into -e, so the output is then NOT reproducible and is STILL
#  INSECURE (one machine, one operator, nobody else verified the transcript).
#
#  Testnet / local anvil only (chain ids 31337, 11155111, 84532). Anything else needs a
#  public phase 1 (e.g. Perpetual Powers of Tau) and a public multi-party phase 2.
# =====================================================================================
#  Phase 1: local `powersoftau new bn128 15` + public beacon, or
#           POOL_PTAU=/path/powersOfTau28_hez_final_15.ptau (blake2b-512 checked against
#           the snarkjs README value). Phase 2 stays insecure either way.
#  Phase 2: groth16 setup + public beacon, then `zkey verify` against r1cs + ptau.
#  Outputs: build/*_final.zkey, vkeys/*.json, verifiers/*.sol, SHA256SUMS,
#           ceremony/transcript.txt
# =====================================================================================
set -euo pipefail
PKG="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$PKG/../.." && pwd)"
SNARKJS="node $ROOT/node_modules/snarkjs/build/cli.cjs"
B="$PKG/build"
POWER=15   # 2^15 = 32768 >= 17904 withdraw constraints (+ public inputs)
HERMEZ_15_B2="982372c867d229c236091f767e703253249a9b432c1710b4f326306bfa2428a17b06240359606cfe4d580b10a5a1f63fbed499527069c18ae17060472969ae6e"
BEACON="0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20"   # PUBLIC. INSECURE.
CONTRIB="${POOL_CEREMONY_CONTRIBUTE:-0}"
mkdir -p "$B" "$PKG/vkeys" "$PKG/verifiers" "$PKG/ceremony"
T="$B/ceremony-transcript.txt"
{
  echo "INSECURE DEV CEREMONY transcript"
  echo "snarkjs $(node -p "require('$ROOT/node_modules/snarkjs/package.json').version"), circomlib $(node -p "require('$ROOT/node_modules/circomlib/package.json').version")"
  echo "beacon $BEACON (public; 2^10 iterations)"
  if [ "$CONTRIB" = "1" ]; then
    echo "mode: + random contributions (NOT reproducible, still INSECURE)"
  else
    echo "mode: beacon-only, deterministic: toxic waste is PUBLIC, proofs are FORGEABLE"
  fi
} > "$T"

PTAU="$B/pot${POWER}_final.ptau"
if [ -n "${POOL_PTAU:-}" ]; then
  GOT="$(b2sum -l 512 "$POOL_PTAU" | cut -d' ' -f1)"
  [ "$GOT" = "$HERMEZ_15_B2" ] || { echo "POOL_PTAU blake2b mismatch" >&2; exit 1; }
  cp "$POOL_PTAU" "$PTAU"
  echo "phase1: Hermez powersOfTau28_hez_final_15.ptau, blake2b ok" >> "$T"
elif [ ! -f "$PTAU" ]; then
  echo "phase1: INSECURE-LOCAL powersoftau new bn128 $POWER" >> "$T"
  $SNARKJS powersoftau new bn128 $POWER "$B/pot_0000.ptau"
  if [ "$CONTRIB" = "1" ]; then
    $SNARKJS powersoftau contribute "$B/pot_0000.ptau" "$B/pot_0001.ptau" --name="INSECURE dev 1" -e="ghostpay INSECURE DEV CEREMONY p1 c1"
    $SNARKJS powersoftau contribute "$B/pot_0001.ptau" "$B/pot_0002.ptau" --name="INSECURE dev 2" -e="ghostpay INSECURE DEV CEREMONY p1 c2"
  else
    cp "$B/pot_0000.ptau" "$B/pot_0002.ptau"
  fi
  $SNARKJS powersoftau beacon "$B/pot_0002.ptau" "$B/pot_beacon.ptau" "$BEACON" 10 -n="INSECURE public beacon"
  $SNARKJS powersoftau prepare phase2 "$B/pot_beacon.ptau" "$PTAU"
  rm -f "$B/pot_0000.ptau" "$B/pot_0001.ptau" "$B/pot_0002.ptau" "$B/pot_beacon.ptau"
else
  echo "phase1: reusing existing $(basename "$PTAU")" >> "$T"
fi
echo "ptau sha256 $(sha256sum "$PTAU" | cut -d' ' -f1)" >> "$T"

HEADER='// =====================================================================================
//  INSECURE DEV CEREMONY -- generated by packages/pool-circuits/scripts/ceremony-dev.sh
//  The proving key behind this verifier was made from a PUBLIC beacon only: anyone can
//  forge proofs this contract accepts and DRAIN any pool using it. Testnet / anvil ONLY.
//  snarkjs 0.7.6 Groth16 template (GPL-3.0); only the contract name and this header differ.
//  Regenerate: npm run build:circuits -w @ghostpay/pool-circuits
//  Check:      npm run check:verifiers -w @ghostpay/pool-circuits
// ====================================================================================='

phase2() {  # $1 circuit file stem, $2 contract name
  local c="$1" name="$2"
  $SNARKJS groth16 setup "$B/$c.r1cs" "$PTAU" "$B/${c}_0000.zkey"
  if [ "$CONTRIB" = "1" ]; then
    $SNARKJS zkey contribute "$B/${c}_0000.zkey" "$B/${c}_0001.zkey" --name="INSECURE dev 1" -e="ghostpay INSECURE DEV CEREMONY $c c1"
    $SNARKJS zkey contribute "$B/${c}_0001.zkey" "$B/${c}_0002.zkey" --name="INSECURE dev 2" -e="ghostpay INSECURE DEV CEREMONY $c c2"
  else
    cp "$B/${c}_0000.zkey" "$B/${c}_0002.zkey"
  fi
  $SNARKJS zkey beacon "$B/${c}_0002.zkey" "$B/${c}_final.zkey" "$BEACON" 10 -n="INSECURE public beacon"
  rm -f "$B/${c}_0000.zkey" "$B/${c}_0001.zkey" "$B/${c}_0002.zkey"
  $SNARKJS zkey verify "$B/$c.r1cs" "$PTAU" "$B/${c}_final.zkey" > "$B/${c}.zkey-verify.txt" 2>&1
  grep -q "ZKey Ok!" "$B/${c}.zkey-verify.txt" || { echo "zkey verify failed for $c" >&2; exit 1; }
  $SNARKJS zkey export verificationkey "$B/${c}_final.zkey" "$PKG/vkeys/$c.vkey.json"
  $SNARKJS zkey export solidityverifier "$B/${c}_final.zkey" "$B/${c}.snarkjs.sol"
  { printf '%s\n' "$HEADER"; sed "s/^contract Groth16Verifier {/contract $name {/" "$B/${c}.snarkjs.sol"; } > "$PKG/verifiers/$name.sol"
  grep -q "^contract $name {" "$PKG/verifiers/$name.sol" || { echo "rename failed for $name" >&2; exit 1; }
  {
    echo "phase2 $c: snarkjs zkey verify -> ZKey Ok!"
    echo "  r1cs sha256 $(sha256sum "$B/$c.r1cs" | cut -d' ' -f1)"
    echo "  zkey sha256 $(sha256sum "$B/${c}_final.zkey" | cut -d' ' -f1)"
    echo "  wasm sha256 $(sha256sum "$B/${c}_js/$c.wasm" | cut -d' ' -f1)"
  } >> "$T"
}
phase2 withdraw32 WithdrawVerifier
phase2 commitment RagequitVerifier

cd "$PKG"
sha256sum build/withdraw32.r1cs build/withdraw32_js/withdraw32.wasm build/withdraw32_final.zkey \
          build/commitment.r1cs build/commitment_js/commitment.wasm build/commitment_final.zkey \
          vkeys/withdraw32.vkey.json vkeys/commitment.vkey.json \
          verifiers/WithdrawVerifier.sol verifiers/RagequitVerifier.sol > SHA256SUMS
{
  echo "# INSECURE DEV CEREMONY verifiers: verifyProof selectors"
  for sig in 'verifyProof(uint256[2],uint256[2][2],uint256[2],uint256[9])' 'verifyProof(uint256[2],uint256[2][2],uint256[2],uint256[4])'; do
    sel="$(node -e "const {keccak256,toBytes}=require('$ROOT/node_modules/viem');console.log(keccak256(toBytes(process.argv[1])).slice(0,10))" "$sig")"
    echo "$sel $sig"
  done
} > verifiers/SELECTORS.txt
cp "$T" ceremony/transcript.txt
echo "INSECURE DEV CEREMONY complete. See SHA256SUMS and ceremony/transcript.txt"
