#!/usr/bin/env bash
# Regenerates src/abi/*.ts from compiled forge output of packages/contracts.
# Usage: scripts/gen-abi.sh   (needs `forge` on PATH; honours FOUNDRY_OUT / FOUNDRY_CACHE_PATH)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
pkg="$(dirname "$here")"
contracts="$pkg/../contracts"
out="$pkg/src/abi"
mkdir -p "$out"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

emit() { # contract constName file
  (cd "$contracts" && forge inspect "$1" abi --json) > "$tmp/$1.json"
  node -e '
    const fs = require("node:fs");
    const [name, constName, file, dest] = process.argv.slice(1);
    const abi = JSON.parse(fs.readFileSync(file, "utf8"));
    fs.writeFileSync(dest,
      "// GENERATED by scripts/gen-abi.sh from " + name + " - do not edit by hand.\n" +
      "export const " + constName + " = " + JSON.stringify(abi, null, 2) + " as const;\n");
  ' "$1" "$2" "$tmp/$1.json" "$out/$3.ts"
}

emit PolicyAccount policyAccountAbi policyAccount
emit PolicyAccountFactory policyAccountFactoryAbi policyAccountFactory
if [ -f "$contracts/src/GhostPayPolicyRouter.sol" ]; then
  emit GhostPayPolicyRouter ghostPayPolicyRouterAbi policyRouter
fi
echo "ABIs written to $out"
