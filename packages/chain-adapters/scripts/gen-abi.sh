#!/usr/bin/env bash
# Regenerates src/abi/*.ts from compiled forge output (contracts) and solc (Chainlink interface).
# Usage: scripts/gen-abi.sh   (needs `forge` on PATH, and `solc` on PATH or $SOLC for the aggregator)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
pkg="$(dirname "$here")"
contracts="$pkg/../contracts"
out="$pkg/src/abi"
SOLC="${SOLC:-solc}"
mkdir -p "$out"

emit() { # name constName json-file
  node -e '
    const fs = require("node:fs");
    const [name, constName, file] = process.argv.slice(1);
    const abi = JSON.parse(fs.readFileSync(file, "utf8"));
    const body = JSON.stringify(abi, null, 2);
    fs.writeFileSync(process.argv[4],
      "// GENERATED by scripts/gen-abi.sh from " + name + " - do not edit by hand.\n" +
      "export const " + constName + " = " + body + " as const;\n");
  ' "$1" "$2" "$3" "$out/$4.ts"
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

inspect() { (cd "$contracts" && forge inspect "$1" abi --json) > "$tmp/$1.json"; }
for c in GhostPayRouter GhostPaySweepRelayer IERC5564Announcer IERC20 IERC20Metadata IERC20Permit; do inspect "$c"; done

emit GhostPayRouter ghostPayRouterAbi "$tmp/GhostPayRouter.json" router
emit GhostPaySweepRelayer ghostPaySweepRelayerAbi "$tmp/GhostPaySweepRelayer.json" sweepRelayer
emit IERC5564Announcer erc5564AnnouncerAbi "$tmp/IERC5564Announcer.json" announcer
emit IERC20 erc20Abi "$tmp/IERC20.json" erc20
emit IERC20Metadata erc20MetadataAbi "$tmp/IERC20Metadata.json" erc20Metadata
emit IERC20Permit erc2612PermitAbi "$tmp/IERC20Permit.json" erc2612

"$SOLC" --abi "$here/abi-src/AggregatorV3Interface.sol" -o "$tmp/agg" --overwrite >/dev/null
emit AggregatorV3Interface chainlinkAggregatorAbi "$tmp/agg/AggregatorV3Interface.abi" chainlinkAggregator

"$SOLC" --abi "$here/abi-src/IERC6538Registry.sol" -o "$tmp/reg" --overwrite >/dev/null
emit IERC6538Registry erc6538RegistryAbi "$tmp/reg/IERC6538Registry.abi" erc6538Registry
echo "ABIs written to $out"
